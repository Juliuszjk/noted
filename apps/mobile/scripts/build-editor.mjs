import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createRequire } from 'node:module';

// Bundles each WebView page (entry + HTML template) into one self-contained HTML string
// exported from a generated TypeScript module.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

// KaTeX stylesheet with its woff2 fonts inlined as data URIs (the WebView loads nothing from
// the network). The woff/ttf fallbacks are dropped: every supported WebView reads woff2.
const katexCss = () => {
  const cssPath = require.resolve('katex/dist/katex.min.css');
  const fontsDir = path.join(path.dirname(cssPath), 'fonts');
  return readFileSync(cssPath, 'utf8')
    .replace(/,\s*url\(fonts\/[^)]+\.(?:woff|ttf)\) format\("(?:woff|truetype)"\)/g, '')
    .replace(/url\(fonts\/([^)]+\.woff2)\)/g, (_, file) =>
      `url(data:font/woff2;base64,${readFileSync(path.join(fontsDir, file)).toString('base64')})`);
};

const targets = [
  { entry: 'editor/main.ts', template: 'editor/index.html', out: 'src/editorHtml.generated.ts', name: 'EDITOR_HTML' },
  { entry: 'editor/kdf.ts', template: 'editor/kdf.html', out: 'src/kdfHtml.generated.ts', name: 'KDF_HTML' },
  // The PDF preview / export page (src/PdfPane.tsx), with the note's styles like the editor.
  { entry: 'editor/pdf.ts', template: 'editor/pdf.html', out: 'src/pdfHtml.generated.ts', name: 'PDF_HTML' },
];

for (const t of targets) {
  const result = await build({
    entryPoints: [path.join(root, t.entry)],
    bundle: true,
    minify: true,
    format: 'iife',
    target: 'es2020',
    write: false,
    define: { 'process.env.NODE_ENV': '"production"' },
    logLevel: 'info',
  });

  // A literal "</script" inside the bundle would end the inline script early.
  const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  const template = readFileSync(path.join(root, t.template), 'utf8');
  // A missing marker would silently ship a page without its styles or code.
  for (const marker of ['/*__BUNDLE__*/', ...(t.template !== 'editor/kdf.html' ? ['/*__CONTENT_CSS__*/'] : [])]) {
    if (!template.includes(marker)) throw new Error(`${t.template} lacks the ${marker} marker`);
  }
  const contentCss = katexCss() + '\n' + readFileSync(path.join(root, '../../packages/editor/content.css'), 'utf8');
  const html = template.replace('/*__BUNDLE__*/', () => js).replace('/*__CONTENT_CSS__*/', () => contentCss);

  const out = path.join(root, t.out);
  writeFileSync(
    out,
    '// Generated by scripts/build-editor.mjs. Do not edit by hand.\n' +
      `export const ${t.name} = ` + JSON.stringify(html) + ';\n',
  );
  console.log('wrote', t.out, (html.length / 1024).toFixed(0) + ' KiB');
}
