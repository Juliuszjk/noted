// Bundles the live note page (src/main.tsx, with its CSS and the KaTeX fonts) into
// apps/api/src/live.generated.ts, which the public server serves as /live.js. Run after
// changing the page or the shared packages it uses (editor, ui, sync, crypto, theme).
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const stub = path.join(root, 'src/config-stub.ts');

// The owner's server addresses (packages/config/server.ts, not in git) stay out of the page.
const noServerAddresses = {
  name: 'no-server-addresses',
  setup(b) {
    b.onResolve({ filter: /^\.\/server(\.ts)?$/ }, (args) => (args.importer.includes(`${path.sep}config${path.sep}`) ? { path: stub } : undefined));
  },
};

const result = await build({
  entryPoints: [path.join(root, 'src/main.tsx')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  write: false,
  outdir: path.join(root, 'dist-live'),
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  // Only woff2 (every current browser reads it), inlined: the page loads nothing else.
  loader: { '.woff2': 'dataurl', '.woff': 'empty', '.ttf': 'empty' },
  plugins: [noServerAddresses],
  logLevel: 'warning',
});

const js = result.outputFiles.find((f) => f.path.endsWith('.js')).text;
const css = result.outputFiles.find((f) => f.path.endsWith('.css'))?.text ?? '';
if (!css.includes('.ProseMirror') || !css.includes('KaTeX')) throw new Error('The page CSS lacks the editor or KaTeX styles');
const page = `(()=>{const s=document.createElement("style");s.textContent=${JSON.stringify(css)};document.head.appendChild(s)})();\n${js}`;
// Personal data must never ship in a public file.
const server = (() => { try { return fileURLToPath(new URL('../../../packages/config/server.ts', import.meta.url)); } catch { return null; } })();
if (server) {
  const { readFileSync, existsSync } = await import('node:fs');
  if (existsSync(server)) {
    for (const [, url] of readFileSync(server, 'utf8').matchAll(/'(https?:\/\/[^']+)'/g)) {
      const host = new URL(url).hostname;
      if (host !== 'localhost' && page.includes(host)) throw new Error(`The page contains the server address ${host}`);
    }
  }
}
const out = path.resolve(root, '../api/src/live.generated.ts');
writeFileSync(out, `// Generated by apps/web/scripts/build-live.mjs; do not edit.\nexport const LIVE_JS = ${JSON.stringify(page)};\n`);
console.log(`wrote apps/api/src/live.generated.ts ${Math.round(page.length / 1024)} KiB`);
