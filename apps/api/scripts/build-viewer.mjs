// Bundles the published note viewer (viewer/viewer.ts) into src/viewer.generated.ts, which
// the public server serves as /viewer.js. Run after changing the viewer or @noted/crypto.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const result = await build({
  entryPoints: [`${root}viewer/viewer.ts`],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  write: false,
});
const js = result.outputFiles[0].text;
writeFileSync(`${root}src/viewer.generated.ts`, `// Generated by scripts/build-viewer.mjs; do not edit.\nexport const VIEWER_JS = ${JSON.stringify(js)};\n`);
console.log(`wrote src/viewer.generated.ts ${Math.round(js.length / 1024)} KiB`);
