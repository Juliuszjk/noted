// Is a colour light? (relative luminance), e.g. to pick dark or light status bar icons.
export const isLightColor = (hex: string): boolean => {
  const n = parseInt(hex.replace('#', '').slice(0, 6), 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((c) => {
    const v = c / 255;
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b > 0.4;
};

// CSS variable -> theme role. The first names predate the theme package and are used
// everywhere; keep them.
const CSS_VARS: [string, keyof ThemeColors][] = [
  ['--bg-base', 'background'],
  ['--bg-surface-low', 'surface_container_low'],
  ['--bg-surface', 'surface_container'],
  ['--bg-surface-high', 'surface_container_high'],
  ['--bg-surface-highest', 'surface_container_highest'],
  ['--text-main', 'on_surface'],
  ['--text-muted', 'on_surface_variant'],
  ['--primary', 'primary'],
  ['--primary-fg', 'on_primary'],
  ['--primary-container', 'primary_container'],
  ['--on-primary-container', 'on_primary_container'],
  ['--secondary-container', 'secondary_container'],
  ['--on-secondary-container', 'on_secondary_container'],
  ['--border-focus', 'outline'],
  ['--border', 'outline_variant'],
  ['--error', 'error'],
];

const HEX = /^#[0-9a-f]{6}([0-9a-f]{2})?$/i;

export const themeToCssVars = (theme: ThemeColors): Record<string, string> =>
  Object.fromEntries(CSS_VARS.map(([name, role]) => [name, theme[role]]));

export const themeToCss = (theme: ThemeColors): string =>
  `:root {\n${CSS_VARS.map(([name, role]) => `  ${name}: ${theme[role]};`).join('\n')}\n}\n`;

const fill = (data: Record<string, unknown>, base: ThemeColors): ThemeColors => {
  const theme = { ...base };
  for (const role of Object.keys(base) as (keyof ThemeColors)[]) {
    const value = data[role];
    if (typeof value === 'string' && HEX.test(value.trim())) theme[role] = value.trim();
  }
  return theme;
};

// Reads a theme file (JSON with role names, as the matugen template writes it). Unknown or
// malformed values fall back to the default, so a broken file can never break the UI.
export const parseTheme = (text: string): ThemeColors => {
  let data: Record<string, unknown> = {};
  try {
    const parsed = JSON.parse(text);
    if (parsed && typeof parsed === 'object') data = (parsed.colors ?? parsed) as Record<string, unknown>;
  } catch {
    return DEFAULT_THEME;
  }
  return fill(data, DEFAULT_THEME);
};

// The theme for a mode. `file` = the matugen theme file (or null): its top-level roles are the
// scheme matugen is in ("auto"), its `light` / `dark` objects both schemes (newer template).
// `systemDark` = the system's dark mode, used when there is no file.
export const resolveTheme = (mode: ThemeMode, file: string | null, systemDark: boolean): ThemeColors => {
  let data: Record<string, unknown> | null = null;
  try {
    const parsed = file ? JSON.parse(file) : null;
    if (parsed && typeof parsed === 'object') data = parsed;
  } catch {
    data = null;
  }
  const scheme = (name: 'light' | 'dark') => {
    const part = data?.[name];
    if (part && typeof part === 'object') return fill(part as Record<string, unknown>, name === 'light' ? LIGHT_THEME : DEFAULT_THEME);
    return name === 'light' ? LIGHT_THEME : DEFAULT_THEME;
  };
  const preset = THEME_PRESETS.find((p) => p.id === mode);
  if (preset) return preset.colors;
  if (mode === 'light') return scheme('light');
  if (mode === 'dark') return scheme('dark');
  if (data && typeof data.background === 'string') return fill(data, DEFAULT_THEME);
  return systemDark ? scheme('dark') : scheme('light');
};
